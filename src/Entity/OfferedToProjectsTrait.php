namespace c975L\PilotBundle\Entity;

use Doctrine\Common\Collections\Collection;

// The projects something is offered on, the using entity mapping its own $projects collection
trait OfferedToProjectsTrait
{
    /** @return Collection<int, Project> */
    public function getProjects(): Collection
    {
        return $this->projects;
    }

    public function addProject(Project $project): static
    {
        if (!$this->projects->contains($project)) {
            $this->projects->add($project);
        }

        return $this;
    }

    public function removeProject(Project $project): static
    {
        $this->projects->removeElement($project);

        return $this;
    }

    // Whether a project offers it
    public function isOfferedTo(Project $project): bool
    {
        return $this->projects->contains($project);
    }
}
